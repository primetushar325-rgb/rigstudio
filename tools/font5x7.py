def glyph(character: str) -> tuple[str, ...]:
    """The bitmap for one character; unknown characters render as a hollow box."""
    return _RAW.get(character.upper(), ("#####", "#...#", "#...#", "#...#", "#...#", "#...#", "#####"))


def text_width(text: str, scale: int = 1) -> int:
    if not text:
        return 0
    return (len(text) * ADVANCE - 1) * scale


def text_height(scale: int = 1) -> int:
    return GLYPH_HEIGHT * scale
